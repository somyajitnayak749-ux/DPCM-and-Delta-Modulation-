def delta_modulate(x, delta, x0=0.0):
    """Linear delta modulator: x_hat(n) = x_hat(n-1) +/- delta."""
    N = len(x)
    x_hat, bits = np.zeros(N), np.zeros(N, dtype=int)
    prev = x0
    for n in range(N):
        b = 1 if x[n] >= prev else -1
        prev = prev + b * delta
        x_hat[n] = prev
        bits[n] = b
    return x_hat, bits


