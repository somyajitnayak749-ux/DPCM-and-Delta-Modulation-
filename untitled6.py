# 6. Mandatory Validation: +/-delta step integrity
# ============================================================================
def validate_step_changes(x_hat, delta, tol=1e-9):
    """Check that every output sample changes by exactly +delta or -delta."""
    steps = np.diff(x_hat)
    ok = np.all(np.isclose(np.abs(steps), delta, atol=tol))
    max_dev = np.max(np.abs(np.abs(steps) - delta))
    return ok, max_dev


