# 5. Task 18 (Optional): Adaptive Delta Modulation
# ============================================================================
def adaptive_delta_modulate(x, delta_min, delta_max, growth=1.5, decay=0.6, x0=0.0):
    """
    Adaptive delta modulator: step grows (x growth) on same-sign bit runs
    (to chase fast slopes) and shrinks (x decay) on sign reversals (to keep
    granular noise low), clamped to [delta_min, delta_max].
    """
    N = len(x)
    x_hat = np.zeros(N)
    bits = np.zeros(N, dtype=int)
    deltas = np.zeros(N)
    prev, delta, last_bit = x0, delta_min, 0
    for n in range(N):
        b = 1 if x[n] >= prev else -1
        delta = min(delta * growth, delta_max) if b == last_bit else max(delta * decay, delta_min)
        prev = prev + b * delta
        x_hat[n], bits[n], deltas[n] = prev, b, delta
        last_bit = b
    return x_hat, bits, deltas


