def make_sine(freq, fs, duration=1.0, amplitude=1.0):
    """Generate n, t, x for x(n) = A*sin(2*pi*freq*n/fs)."""
    n = np.arange(int(round(fs * duration)))
    t = n / fs
    x = amplitude * np.sin(2 * np.pi * freq * t)
    return n, t, x


def uniform_quantize(x, levels, vmax):
    """
    Uniform mid-rise quantizer over [-vmax, +vmax] with `levels` levels.
    step = 2*vmax/levels; output is clipped to the representable range.
    """
    x = np.asarray(x, dtype=float)
    step = 2.0 * vmax / levels
    idx = np.floor((x + vmax) / step)
    idx = np.clip(idx, 0, levels - 1)
    xq = -vmax + (idx + 0.5) * step
    return xq


def no_overload_threshold(freq, fs, amplitude=1.0):
    """Delta >= 2*pi*f*A/fs is required so the DM staircase can track a
    sinusoid of the given frequency/amplitude without slope overload."""
    return 2 * np.pi * freq * amplitude / fs


