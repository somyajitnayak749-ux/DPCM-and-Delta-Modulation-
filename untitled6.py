def dpcm_first_order(x, levels, a=None):
    """
    First-order closed-loop DPCM encoder/decoder.
    Predictor: x_pred(n) = a*x_hat(n-1). If `a` is not given, it is estimated
    from the signal's own (biased) autocorrelation: a = R(1)/R(0).
    Returns: x_pred, x_hat, e (pre-quantization error), eq (quantized error), a
    """
    N = len(x)
    if a is None:
        R0 = np.sum(x[:-1] ** 2)
        R1 = np.sum(x[1:] * x[:-1])
        a = R1 / R0  # first-order predictor coefficient

    x_hat = np.zeros(N)   # decoder output (reconstructed)
    x_pred = np.zeros(N)  # predicted samples
    e, eq = np.zeros(N), np.zeros(N)  # error before / after quantization

    e_openloop = x[1:] - a * x[:-1]
    vmax = 1.3 * np.max(np.abs(e_openloop))  # size quantizer to the error range

    for n in range(N):
        x_pred[n] = a * x_hat[n - 1] if n > 0 else 0.0
        e[n] = x[n] - x_pred[n]
        eq[n] = uniform_quantize(np.array([e[n]]), levels, vmax)[0]
        x_hat[n] = x_pred[n] + eq[n]

    return x_pred, x_hat, e, eq, a


def pcm_quantize(x, levels):
    """Direct (memoryless) PCM quantization of x."""
    vmax = np.max(np.abs(x)) * 1.05
    return uniform_quantize(x, levels, vmax), vmax


